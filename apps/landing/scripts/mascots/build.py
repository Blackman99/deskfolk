"""Pack the Mochi and Pudding layers rendered by render.sh for the home page.

Run: python3 scripts/mascots/build.py   (needs Pillow; reads film-out/mascots/<who>/)

Every 512 px layer is cropped to what it draws, scaled to an EDGE px square and saved as a lossy
WebP in static/mascots/<who>/<layer>.webp. src/lib/home/mascot-assets.ts gets each layer's box in
the square ([x, y, w, h] fractions) and the points the companions move about: shoulders, hands,
mouth, eyes, the top of the head, feet and Pudding's antenna tip, as [x, y] fractions from the
square's top-left corner.
"""
import json, math, os
from PIL import Image

EDGE = 320  # the companions are drawn at most ~150 CSS px; this covers 2x with room
ALPHA = 12  # a pixel counts as drawn above this alpha
PAD = 2  # px of the 512 render kept around each crop, so soft edges are not cut

here = os.path.dirname(os.path.abspath(__file__))
landing = os.path.normpath(os.path.join(here, '..', '..'))
src_root = os.path.join(landing, 'film-out', 'mascots')
static_root = os.path.join(landing, 'static', 'mascots')
ts_out = os.path.join(landing, 'src', 'lib', 'home', 'mascot-assets.ts')

FACE = ['eyes-dot', 'eyes-happy', 'eyes-wink', 'eyes-closed', 'mouth-smile', 'mouth-open', 'mouth-cat']
WHO = {
    'pudding': ['body', 'arm-l', 'arm-r', *FACE, 'acc-antenna'],
    'mochi': ['body', 'arm-l', 'arm-r', *FACE],
}


def drawn(im):
    return im.getchannel('A').point(lambda v: 255 if v > ALPHA else 0)


def frac(v, n):
    return round(v / n, 4)


def farthest(mask, point):
    """The drawn pixel farthest from `point` (fractions): the tip of an arm from its shoulder."""
    w, h = mask.size
    px, py = point[0] * w, point[1] * h
    data = mask.load()
    best, at = -1.0, (0, 0)
    for y in range(0, h, 2):
        for x in range(0, w, 2):
            if data[x, y]:
                d = math.hypot(x - px, y - py)
                if d > best:
                    best, at = d, (x, y)
    return [frac(at[0], w), frac(at[1], h)]


layers, geometry = {}, {}
total = 0
for who, names in WHO.items():
    src = os.path.join(src_root, who)
    out = os.path.join(static_root, who)
    os.makedirs(out, exist_ok=True)
    meta = json.load(open(os.path.join(src, 'meta.json')))
    boxes = {}
    masks = {}
    for name in names:
        im = Image.open(os.path.join(src, name + '.png')).convert('RGBA')
        n = im.width
        mask = drawn(im)
        masks[name] = mask
        x0, y0, x1, y1 = mask.getbbox()
        x0, y0 = max(0, x0 - PAD), max(0, y0 - PAD)
        x1, y1 = min(n, x1 + PAD), min(n, y1 + PAD)
        scale = EDGE / n
        crop = im.crop((x0, y0, x1, y1))
        size = (max(1, round((x1 - x0) * scale)), max(1, round((y1 - y0) * scale)))
        crop = crop.resize(size, Image.LANCZOS)
        path = os.path.join(out, name + '.webp')
        crop.save(path, 'WEBP', quality=88, method=6)
        total += os.path.getsize(path)
        boxes[name] = [frac(x0, n), frac(y0, n), frac(x1 - x0, n), frac(y1 - y0, n)]
    layers[who] = boxes

    mx0, my0, mx1, my1 = masks['mouth-smile'].getbbox()
    n = masks['mouth-smile'].width
    g = {
        'shoulderL': meta['shoulder_l'],
        'shoulderR': meta['shoulder_r'],
        'handL': farthest(masks['arm-l'], meta['shoulder_l']),
        'handR': farthest(masks['arm-r'], meta['shoulder_r']),
        'mouth': [frac((mx0 + mx1) / 2, n), frac((my0 + my1) / 2, n)],
        'eyes': meta['eyes'],
        'headTop': meta['head_top'],
        'feet': meta['feet'],
    }
    if 'acc-antenna' in masks:
        ax0, ay0, ax1, ay1 = masks['acc-antenna'].getbbox()
        g['antennaTip'] = [frac((ax0 + ax1) / 2, n), frac(ay0, n)]
    geometry[who] = g

lines = [
    '// Generated by scripts/mascots/build.py from the renders of scripts/mascots/render.sh.',
    '// Do not edit by hand: change the renderer and run both scripts again.',
    '',
    '/** Each layer of each companion: its box in the square, [x, y, w, h] fractions; the picture is static/mascots/<who>/<layer>.webp. */',
    'export const MASCOT_LAYERS = ' + json.dumps(layers, indent=2) + ' as const;',
    '',
    '/** Where the parts turn, hold and rest, as [x, y] fractions of the square from its top-left corner. */',
    'export const MASCOT_GEOMETRY = ' + json.dumps(geometry, indent=2) + ' as const;',
    '',
]
with open(ts_out, 'w') as f:
    f.write('\n'.join(lines))
print(f'wrote {os.path.relpath(ts_out, landing)} and {sum(len(v) for v in WHO.values())} layers, {total} bytes of WebP')
