"""Pack the folk avatar's layers into src/folk-avatar-assets.ts.

The layers are the task map's characters seen by the avatar's camera:
  FIG_VIEW=avatar Blender -b --factory-startup --python apps/messenger/scripts/map-figures/figures.py -- LAYER_DIR
Run: python3 build.py LAYER_DIR   (needs Pillow)
Each 512 px PNG is scaled to EDGE px and stored as a lossy WebP with its alpha intact. The points
the messenger animates about (shoulders and hands, the antenna's foot from meta.json, the mouth's
centre from its layer) are written next to the layers as fractions of the square.
"""
import base64, io, json, os, sys
from PIL import Image

EDGE = 160  # the largest avatar on screen is 56 CSS px; this covers it at 2x with room
# folk-avatar.ts's FOLK_CHARACTERS, and the parts each one may have beyond its body and arms
CHARACTERS = ['pudding', 'taro', 'sakura', 'matcha', 'caramel', 'sesame', 'blueberry']
OWN = ['body', 'arm-l', 'arm-r', 'held-l', 'held-r', 'front', 'antenna']
SHARED = [
    'eyes-dot', 'eyes-happy', 'eyes-wink', 'eyes-closed',
    'mouth-smile', 'mouth-open', 'mouth-cat',
]

src = sys.argv[1] if len(sys.argv) > 1 else 'avatar-layers'
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'folk-avatar-assets.ts')
have = lambda name: os.path.exists(os.path.join(src, name + '.png'))
LAYERS = [f'{c}-{part}' for c in CHARACTERS for part in OWN if have(f'{c}-{part}')] + SHARED
for c in CHARACTERS:
    for part in ('body', 'arm-l', 'arm-r'):
        assert have(f'{c}-{part}'), f'{c}-{part} missing from {src}'
lines = [
    '// Generated by scripts/folk-avatar/build.py from the Blender renders of',
    '// apps/messenger/scripts/map-figures/figures.py (FIG_VIEW=avatar).',
    '// Do not edit by hand: change the renderer and run both scripts again.',
    '',
    f'export const FOLK_LAYER_EDGE = {EDGE};',
    '',
    '/** Transparent WebP layers, base64, all framed alike so any character, eyes and mouth stack. */',
    'export const FOLK_LAYERS = {',
]
total = 0
for name in LAYERS:
    im = Image.open(os.path.join(src, name + '.png')).convert('RGBA').resize((EDGE, EDGE), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, 'WEBP', quality=90, method=6)
    b64 = base64.b64encode(buf.getvalue()).decode()
    total += len(b64)
    lines.append(f'  "{name}": "{b64}",')
meta = json.load(open(os.path.join(src, 'meta.json')))
mouth = Image.open(os.path.join(src, 'mouth-smile.png')).getchannel('A').point(lambda v: 255 if v > 24 else 0)
x0, y0, x1, y1 = mouth.getbbox()
geometry = {
    'shoulderL': meta['shoulder_l'],
    'shoulderR': meta['shoulder_r'],
    'handL': meta['hand_l'],
    'handR': meta['hand_r'],
    'antenna': meta['head_top'],
    'feet': meta['feet'],
    'mouth': [round((x0 + x1) / 2 / mouth.width, 4), round((y0 + y1) / 2 / mouth.height, 4)],
}
lines += [
    '} as const;',
    '',
    'export type FolkLayer = keyof typeof FOLK_LAYERS;',
    '',
    '/** Where the parts turn and flip, as [x, y] fractions of the square from its top-left corner. */',
    'export const FOLK_GEOMETRY = ' + json.dumps(geometry) + ' as const;',
    '',
]
with open(out, 'w') as f:
    f.write('\n'.join(lines))
print(f'wrote {os.path.normpath(out)}: {len(LAYERS)} layers, {total} base64 chars')
